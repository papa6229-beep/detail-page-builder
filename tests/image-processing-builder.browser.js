async (page) => {
  let step = 'setup';
  try {
  page.setDefaultTimeout(8000);
  await page.goto('http://127.0.0.1:3000/');
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  assert(await page.getByRole('button', { name: '전체 이미지 보정', exact: true }).count() === 1, 'Builder toolbar must expose sequential image processing');
  const fixture = await page.evaluate(() => {
    const c = document.createElement('canvas'); c.width = 320; c.height = 400;
    const x = c.getContext('2d'); x.fillStyle = '#e2e4e5'; x.fillRect(0, 0, 320, 400);
    x.fillStyle = '#ba3054'; x.beginPath(); x.roundRect(105, 65, 110, 260, 45); x.fill();
    return c.toDataURL().split(',')[1];
  });
  const main = page.getByRole('group', { name: 'Main Image 이미지 첨부', exact: true });
  await main.locator('input[type=file]').setInputFiles({ name: 'main.png', mimeType: 'image/png', buffer: Buffer.from(fixture, 'base64') });
  const original = await main.locator('img').getAttribute('src');
  await main.getByRole('button', { name: '누끼·보정', exact: true }).click();
  step = 'initial editor';
  const dialog = page.getByRole('dialog', { name: '이미지 보정', exact: true });
  const apply = dialog.getByRole('button', { name: '이 이미지 적용', exact: true });
  await apply.waitFor({ timeout: 60000 });
  await page.waitForFunction(() => !document.querySelector('button[data-image-apply]').disabled, null, { timeout: 60000 });
  const boxAppearance = await dialog.locator('.shadow-move').evaluate(e => { const s = getComputedStyle(e); return { border: s.borderTopWidth, background: s.backgroundColor, label: e.textContent.trim() }; });
  assert(boxAppearance.border === '0px' && boxAppearance.background === 'rgba(0, 0, 0, 0)' && boxAppearance.label === '', 'Editing rectangle must not cover the shadow');
  assert(await main.locator('img').getAttribute('src') === original, 'Previewing edits must leave the builder source unchanged');
  await dialog.getByRole('slider', { name: '그림자 진하기', exact: true }).fill('68');
  await dialog.getByRole('button', { name: '그림자 회전', exact: true }).focus();
  await page.keyboard.press('ArrowRight');
  step = 'opacity update';
  await page.waitForFunction(() => document.querySelector('button[data-image-apply]')?.disabled === false);
  await apply.click(); await dialog.waitFor({ state: 'detached' });
  const processed = await main.locator('img').getAttribute('src');
  assert(processed !== original && processed.startsWith('data:image/png;base64,'), 'Apply must update the target image with the processed PNG');
  await page.getByRole('button', { name: '임시 저장', exact: true }).click();
  await page.waitForFunction(() => Boolean(localStorage.getItem('builder_temp_save')));
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('builder_temp_save')));
  assert(saved.mainImage === processed && saved.imageEdits.mainImage.original === original && saved.imageEdits.mainImage.shadow.opacity === 68 && saved.imageEdits.mainImage.shadow.angle === 1, 'Temporary save must preserve the processed image, original, strength and rotation');
  await page.reload();
  await page.getByRole('button', { name: '불러오기', exact: true }).click();
  const library = page.getByRole('dialog', { name: '작업 보관함', exact: true });
  await library.getByRole('button', { name: '이전 임시 저장 불러오기', exact: true }).click();
  await library.waitFor({ state: 'detached' });
  await page.waitForFunction(processed => document.querySelector('[aria-label="Main Image 이미지 첨부"] img')?.getAttribute('src') === processed, processed);
  await main.getByRole('button', { name: '누끼·보정', exact: true }).click();
  step = 'reopen original';
  await page.waitForFunction(() => document.querySelector('button[data-image-apply]')?.disabled === false, null, { timeout: 60000 });
  assert(await dialog.getByRole('slider', { name: '그림자 진하기', exact: true }).inputValue() === '68', 'Reopening must preserve per-image settings');
  assert(await dialog.locator('canvas').getAttribute('data-angle') === '1', 'Reopening must preserve per-image rotation');
  await dialog.getByRole('button', { name: '원본 사용', exact: true }).click(); await dialog.waitFor({ state: 'detached' });
  assert(await main.locator('img').getAttribute('src') === original, 'Restore must recover exact original bytes');
  const thumb = page.getByRole('group', { name: 'Thumbnail 이미지 첨부', exact: true });
  await thumb.locator('input[type=file]').setInputFiles({ name: 'thumbnail.png', mimeType: 'image/png', buffer: Buffer.from(fixture, 'base64') });
  await page.getByRole('button', { name: '전체 이미지 보정', exact: true }).click();
  step = 'batch';
  await dialog.getByText('1 / 2', { exact: true }).waitFor();
  await dialog.getByRole('button', { name: '건너뛰기', exact: true }).click();
  await dialog.getByText('2 / 2', { exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('button[data-image-apply]')?.disabled === false, null, { timeout: 60000 });
  await apply.click(); await dialog.waitFor({ state: 'detached' });
  assert(await main.locator('img').getAttribute('src') === original && await thumb.locator('img').getAttribute('src') !== original, 'Sequential processing must apply only the approved slot');
  await thumb.getByRole('button', { name: '누끼·보정', exact: true }).click();
  step = 'cancel';
  await page.waitForFunction(() => document.querySelector('button[data-image-apply]')?.disabled === false, null, { timeout: 60000 });
  await dialog.getByRole('slider', { name: '그림자 진하기', exact: true }).fill('10');
  await dialog.getByRole('button', { name: '편집 닫기', exact: true }).click();
  await dialog.waitFor({ state: 'detached' });
  const stillProcessed = await thumb.locator('img').getAttribute('src');
  assert(stillProcessed !== original, 'Closing must preserve the already applied image');
  await thumb.locator('input[type=file]').setInputFiles({ name: 'replacement.png', mimeType: 'image/png', buffer: Buffer.from(fixture, 'base64') });
  await page.waitForFunction(original => document.querySelector('[aria-label="Thumbnail 이미지 첨부"] img')?.getAttribute('src') === original, original);
  await thumb.getByRole('button', { name: '누끼·보정', exact: true }).click();
  step = 'replace';
  await page.waitForFunction(() => document.querySelector('button[data-image-apply]')?.disabled === false, null, { timeout: 60000 });
  assert(await dialog.getByRole('slider', { name: '그림자 진하기', exact: true }).inputValue() === '45', 'Replacing a file must clear previous adjustments');
  await dialog.getByRole('button', { name: '편집 닫기', exact: true }).click();
  const result = { passed: 10, isolated: await page.evaluate(() => crossOriginIsolated) };
  await page.evaluate(result => { window.__imageProcessingVerification = result; }, result);
  return result;
  } catch (error) {
    const message = `${step}: ${error.message}`;
    await page.evaluate(message => { window.__imageProcessingVerification = { error: message }; }, message);
    throw new Error(message);
  }
}
