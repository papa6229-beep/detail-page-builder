async (page) => {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.goto('http://127.0.0.1:3001/image-lab.html');
  const fixture = await page.evaluate(() => {
    const c = document.createElement('canvas'); c.width = 640; c.height = 320;
    const x = c.getContext('2d'); x.fillStyle = '#e2e4e5'; x.fillRect(0, 0, 640, 320);
    x.fillStyle = '#905949'; x.beginPath(); x.roundRect(90, 165, 380, 65, 25); x.fill();
    x.beginPath(); x.ellipse(470, 160, 42, 70, -.3, 0, Math.PI * 2); x.fill();
    return c.toDataURL().split(',')[1];
  });
  await page.locator('input[type=file]').setInputFiles({ name: 'drag-check.png', mimeType: 'image/png', buffer: Buffer.from(fixture, 'base64') });
  await page.getByRole('button', { name: '테스트 실행', exact: true }).click();
  await page.getByRole('link', { name: 'PNG 저장 ↗', exact: true }).last().waitFor({ timeout: 60000 });
  assert(await page.locator('.shadow-sliders input').count() === 2, 'Only strength and softness belong in the shadow panel');
  const canvas = page.getByRole('img', { name: '톤·그림자 적용', exact: true });
  const cutoutUrl = await page.locator('img[alt="누끼 결과"]').getAttribute('src');
  const removalTime = await page.locator('article footer').nth(1).textContent();
  const move = page.getByRole('button', { name: '그림자 이동', exact: true });
  const box = await move.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 32, box.y + box.height / 2 + 16, { steps: 3 });
  await page.waitForFunction(() => Number(document.querySelector('canvas[aria-label="톤·그림자 적용"]').dataset.offsetX) > 0);
  assert(await canvas.getAttribute('data-dragging') === 'true', 'The image must repaint while the pointer is still held down');
  await page.mouse.up();
  const afterMove = Number(await canvas.getAttribute('data-offset-x'));
  const handle = await page.getByRole('button', { name: '그림자 크기 조절', exact: true }).boundingBox();
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2);
  await page.mouse.down(); await page.mouse.move(handle.x + 35, handle.y + 22, { steps: 3 });
  await page.waitForFunction(() => Number(document.querySelector('canvas[aria-label="톤·그림자 적용"]').dataset.shadowWidth) > 100 && Number(document.querySelector('canvas[aria-label="톤·그림자 적용"]').dataset.shadowDepth) > 100);
  await page.mouse.up();
  const rotation = await page.getByRole('button', { name: '그림자 회전', exact: true }).boundingBox();
  const frame = await page.locator('.shadow-transform').boundingBox();
  const center = { x: frame.x + frame.width / 2, y: frame.y + frame.height / 2 };
  const start = { x: rotation.x + rotation.width / 2, y: rotation.y + rotation.height / 2 };
  const angle = Math.atan2(start.y - center.y, start.x - center.x) + Math.PI / 6;
  const radius = Math.hypot(start.x - center.x, start.y - center.y);
  await page.mouse.move(start.x, start.y); await page.mouse.down();
  await page.mouse.move(center.x + Math.cos(angle) * radius, center.y + Math.sin(angle) * radius, { steps: 4 });
  await page.waitForFunction(() => Number(document.querySelector('canvas[aria-label="톤·그림자 적용"]').dataset.angle) > 10);
  assert(await canvas.getAttribute('data-dragging') === 'true', 'Rotation must repaint before releasing the pointer');
  await page.mouse.up();
  const widthHandle = await page.getByRole('button', { name: '그림자 가로 크기 조절', exact: true }).boundingBox();
  const previousWidth = Number(await canvas.getAttribute('data-shadow-width'));
  const radians = Number(await canvas.getAttribute('data-angle')) * Math.PI / 180;
  await page.mouse.move(widthHandle.x + widthHandle.width / 2, widthHandle.y + widthHandle.height / 2);
  await page.mouse.down();
  await page.mouse.move(widthHandle.x + widthHandle.width / 2 + Math.cos(radians) * 20, widthHandle.y + widthHandle.height / 2 + Math.sin(radians) * 20, { steps: 3 });
  await page.waitForFunction(previous => Number(document.querySelector('canvas[aria-label="톤·그림자 적용"]').dataset.shadowWidth) > previous, previousWidth);
  await page.mouse.up();
  await page.getByRole('slider', { name: '그림자 진하기', exact: true }).fill('75');
  await page.waitForFunction(() => document.querySelector('canvas[aria-label="톤·그림자 적용"]').dataset.opacity === '75');
  await page.getByRole('button', { name: '그림자 이동', exact: true }).focus();
  await page.keyboard.press('ArrowRight');
  await page.waitForFunction(previous => Number(document.querySelector('canvas[aria-label="톤·그림자 적용"]').dataset.offsetX) > previous, afterMove);
  assert(await page.locator('img[alt="누끼 결과"]').getAttribute('src') === cutoutUrl && await page.locator('article footer').nth(1).textContent() === removalTime, 'Dragging must reuse the existing cutout');
  await page.getByRole('checkbox', { name: '원본 크기(100%)', exact: true }).check();
  await page.waitForFunction(() => document.querySelector('canvas[aria-label="톤·그림자 적용"]').width === 640);
  await page.waitForFunction(() => document.querySelectorAll('a[download$="_finished.png"]').length === 1);
  const exported = await page.evaluate(async () => {
    const link = document.querySelector('a[download$="_finished.png"]');
    const image = await createImageBitmap(await (await fetch(link.href)).blob());
    const c = document.createElement('canvas'); c.width = image.width; c.height = image.height;
    const x = c.getContext('2d'); x.drawImage(image, 0, 0); image.close();
    const output = x.getImageData(0, 0, c.width, c.height).data;
    const preview = document.querySelector('canvas[aria-label="톤·그림자 적용"]').getContext('2d').getImageData(0, 0, c.width, c.height).data;
    let maxDiff = 0;
    for (let i = 0; i < output.length; i++) maxDiff = Math.max(maxDiff, Math.abs(output[i] - preview[i]));
    return { width: c.width, height: c.height, maxDiff };
  });
  assert(exported.width === 640 && exported.height === 320 && exported.maxDiff <= 2, 'Saved PNG must match the live preview at original dimensions');
  await page.getByRole('button', { name: '그림자 기본값', exact: true }).click();
  await page.waitForFunction(() => { const d = document.querySelector('canvas[aria-label="톤·그림자 적용"]').dataset; return d.offsetX === '0' && d.offsetY === '0' && d.shadowWidth === '100' && d.shadowDepth === '100' && d.opacity === '45' && d.angle === '0'; });
  await page.getByRole('checkbox', { name: '그림자 적용', exact: true }).uncheck();
  assert(await move.count() === 0, 'Turning the shadow off must hide the editing handles');
  return { passed: 11, exported };
}
